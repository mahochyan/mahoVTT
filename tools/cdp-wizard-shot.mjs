import { writeFileSync } from 'node:fs';
const port = process.argv[2] || '9333';
const base = process.argv[3] || 'http://127.0.0.1:3021';
const targets = await (await fetch(`http://127.0.0.1:${port}/json`)).json();
const page = targets.find((t) => t.type === 'page');
const ws = new WebSocket(page.webSocketDebuggerUrl);
let id = 0; const pending = new Map();
ws.onmessage = (ev) => { const m = JSON.parse(ev.data); if (m.id && pending.has(m.id)) { pending.get(m.id)(m); pending.delete(m.id); } };
await new Promise((r) => { ws.onopen = r; });
const send = (method, params = {}) => new Promise((resolve) => { const my = ++id; pending.set(my, resolve); ws.send(JSON.stringify({ id: my, method, params })); });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const evalJs = (expression) => send('Runtime.evaluate', { expression, returnByValue: true, awaitPromise: true });
await send('Page.enable');
await send('Emulation.setDeviceMetricsOverride', { width: 1440, height: 1000, deviceScaleFactor: 1, mobile: false, screenWidth: 1440, screenHeight: 1000 });
await send('Page.navigate', { url: base + '/campaigns/new' });
await sleep(1800);
await evalJs('document.querySelector("[data-action=wizard-world]").click()');
await sleep(500);
const shot = await send('Page.captureScreenshot', { format: 'png', captureBeyondViewport: false });
writeFileSync('artifacts/wizard-step2.png', Buffer.from(shot.result.data, 'base64'));
console.log('saved step2');
await send('Page.navigate', { url: base + '/settings' });
await sleep(1600);
const shot2 = await send('Page.captureScreenshot', { format: 'png', captureBeyondViewport: false });
writeFileSync('artifacts/settings.png', Buffer.from(shot2.result.data, 'base64'));
console.log('saved settings');
ws.close();
